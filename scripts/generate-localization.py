"""Validate placeholders and embed the translation catalog in the native executable."""
from pathlib import Path
import json,re,sys
root=Path(__file__).resolve().parents[1]
p=root/'app/Resources/zh-Hans.json'
pairs=json.loads(p.read_text(),object_pairs_hook=list)
assert len({k for k,v in pairs})==len(pairs),'Duplicate localization keys'
for key,value in pairs:
 assert isinstance(value,str) and value,'Missing translation: '+key
 assert sorted(re.findall(r'\{\d+\}',key))==sorted(re.findall(r'\{\d+\}',value)), 'Placeholder mismatch: '+key

def swift(s):
 return json.dumps(s,ensure_ascii=False).replace('\\u0000','\\0')
output='// Generated by scripts/generate-localization.py; edit app/Resources/zh-Hans.json.\nimport Foundation\nenum LocalizationCatalog {\n    static let chinese: [String:String] = [\n'+''.join('        '+swift(k)+': '+swift(v)+',\n' for k,v in pairs)+'    ]\n}\n'
target=root/'app/LocalizationCatalog.swift'
if '--check' in sys.argv:
 assert target.read_text()==output,'Run scripts/generate-localization.py'
else:target.write_text(output)
print(f'Validated {len(pairs)} translations and placeholder sets')
