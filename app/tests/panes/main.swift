import AppKit
_ = NSApplication.shared
var failures = 0
func check(_ value: Bool, _ name: String) { print("\(value ? "PASS" : "FAIL"): \(name)"); if !value { failures += 1 } }
let layout = TerminalPaneLayout(frame:NSRect(x:0,y:0,width:1000,height:600))
let first = NSView(), second = NSView(), third = NSView()
let a = layout.setInitial(first), b = UUID(), c = UUID()
check(layout.paneIDs == [a] && layout.paneFrame(a)?.size == layout.bounds.size,"initial pane fills workspace")
check(layout.split(a,with:second,direction:.right,newID:b),"split inserts independent view")
check(layout.paneFrame(a)!.maxX < layout.paneFrame(b)!.minX && abs(layout.paneFrame(a)!.width - layout.paneFrame(b)!.width) < 2,"vertical divider separates equal left/right panes")
check(layout.split(b,with:third,direction:.down,newID:c),"nested orthogonal split")
check(layout.paneIDs == [a,b,c] && layout.focusedID == c,"depth-first pane order and new-pane focus")
check(layout.paneFrame(b)!.intersects(layout.paneFrame(c)!) == false,"nested panes do not overlap")
check(layout.paneFrame(b)!.minY > layout.paneFrame(c)!.maxY,"down split places new pane below existing pane")
let outer = layout.subviews.first as! NSSplitView
outer.setPosition(300,ofDividerAt:0)
let originalRatio = layout.paneFrame(a)!.width / (layout.bounds.width - outer.dividerThickness)
let before = layout.paneFrame(a)!.width
layout.frame.size = NSSize(width:1400,height:800); layout.needsLayout = true; layout.layoutSubtreeIfNeeded()
check(layout.paneFrame(a)!.width > before && layout.paneFrame(c)!.maxX <= 1400,"workspace resize propagates through nested layout")
let resizedRatio = layout.paneFrame(a)!.width / (layout.bounds.width - outer.dividerThickness)
check(abs(originalRatio - resizedRatio) < 0.01,"manual divider ratio survives workspace resize")
layout.equalize()
check(abs(layout.paneFrame(a)!.width - layout.paneFrame(c)!.width) < 2,"equalize resets nested divider ratios")
layout.focus(from:b,direction:.down); check(layout.focusedID == c,"directional focus goes down within nested branch")
layout.focus(from:c,direction:.left); check(layout.focusedID == a,"directional focus crosses nested branch")
let oldWidth = layout.paneFrame(a)!.width
layout.resize(from:c,direction:.right,amount:40)
check(layout.paneFrame(a)!.width > oldWidth,"resize finds nearest matching ancestor divider")
let oldHeight = layout.paneFrame(b)!.height
layout.resize(from:c,direction:.down,amount:30)
check(layout.paneFrame(b)!.height > oldHeight,"vertical resize targets inner horizontal divider")
layout.equalize(); layout.markFocused(c)
layout.focusNext(); check(layout.focusedID == a,"focus cycles across nested panes")
layout.focusNext(backwards:true); check(layout.focusedID == c,"reverse focus cycles")
check(layout.remove(b) === second && layout.paneIDs == [a,c],"closing nested pane returns only its view and collapses branch")
check(layout.paneFrame(c)!.height == layout.bounds.height,"surviving sibling fills collapsed branch")
check(!layout.split(UUID(),with:NSView(),direction:.left) && layout.remove(UUID()) == nil,"unknown pane mutations are rejected")
check(!layout.split(a,with:first,direction:.left),"one view cannot belong to two pane identities")
check(!layout.split(a,with:NSView(),direction:.left,newID:c),"duplicate pane identity rejected")
_ = layout.remove(c)
check(layout.paneIDs == [a] && layout.paneFrame(a)?.size == layout.bounds.size,"closing sibling restores full-size terminal")
_ = layout.remove(a)
check(layout.paneIDs.isEmpty && layout.focusedID == nil && layout.subviews.isEmpty,"last pane leaves empty layout without retained subviews")
let restored = TerminalPaneLayout(frame:NSRect(x:0,y:0,width:1000,height:600))
let ra = UUID(), rb = UUID(), rc = UUID()
let tree = PaneLayoutSnapshot.split(.right,0.3,.leaf(ra),.split(.down,0.65,.leaf(rb),.leaf(rc)))
let decoded = try! JSONDecoder().decode(PaneLayoutSnapshot.self,from:JSONEncoder().encode(tree))
check(decoded == tree,"nested layout JSON preserves directions and ratios")
let views = [ra:NSView(),rb:NSView(),rc:NSView()]
check(restored.restore(decoded,views:views,focused:rb),"restore accepts complete independent pane mapping")
check(restored.paneIDs == [ra,rb,rc] && restored.focusedID == rb,"restore preserves pane order and focused identity")
check(abs(restored.paneFrame(ra)!.width / 999 - 0.3) < 0.01 && restored.paneFrame(rb)!.minY > restored.paneFrame(rc)!.maxY,"restored nested geometry preserves divider and orientation")
let beforeRestore = restored.snapshot()
check(!restored.restore(.split(.right,0.5,.leaf(ra),.leaf(ra)),views:[ra:NSView()],focused:nil) && restored.snapshot() == beforeRestore,"duplicate IDs rejected without disturbing current layout")
check(!restored.restore(tree,views:[ra:NSView()],focused:nil),"missing pane views rejected")
check(!restored.restore(.split(.right,1.2,.leaf(ra),.leaf(rb)),views:[ra:NSView(),rb:NSView()],focused:nil),"out-of-range divider rejected")
var deep = PaneLayoutSnapshot.leaf(ra)
for _ in 0..<33 { deep = .split(.down,0.5,deep,.leaf(UUID())) }
check(!deep.valid(),"excessive nesting rejected")
let replacement = UUID()
check(tree.remapping([ra:replacement]).ids == [replacement,rb,rc],"restore assigns fresh pane identities")
print("RESULT failures=\(failures)"); exit(failures == 0 ? 0 : 1)
